// sitemap lastmod 정직화 — 각 스포크 소스파일의 '최초 커밋일(발행일)'을 slug→date 로 사전생성.
// 왜 최초커밋(발행일)인가: 최종커밋일은 코퍼스 일괄정정(예: 체당금→대지급금)으로 오염되어
// 대다수 페이지가 '오늘'로 찍힘 → 신선도 신호 왜곡. 발행일은 콘텐츠 실제 작성시점이라 정직.
// 재생성: node scripts/generate-sitemap-lastmod.mjs  (일일 배치 후 실행 권장)
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname).replace(/^\/([A-Za-z]:)/, '$1'), '..');
const SPOKE_DIR = path.join(ROOT, 'web', 'src', 'data', 'spoke');
const OUT = path.join(ROOT, 'web', 'src', 'data', 'sitemap-lastmod-generated.ts');

const files = readdirSync(SPOKE_DIR).filter((f) => f.endsWith('.ts'));
const slugDate = {};
const domainLatest = {};
let globalLatest = '2000-01-01';

const objRe = /domain:\s*'([^']+)'[\s\S]{0,400}?slug:\s*'([^']+)'/g;

for (const f of files) {
  const full = path.join(SPOKE_DIR, f);
  // 최초 커밋일(발행일). 파일 rename 대비 --follow.
  let date;
  try {
    const out = execSync(`git log --follow --format=%cs --reverse -- "web/src/data/spoke/${f}"`, {
      cwd: ROOT, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();
    date = out.split('\n')[0].trim();
  } catch {
    date = '';
  }
  if (!/^\d{4}-\d{2}-\d{2}$/.test(date)) continue; // 미커밋 신규파일 등은 스킵(런타임 fallback)
  const txt = readFileSync(full, 'utf8');
  let m;
  while ((m = objRe.exec(txt))) {
    const domain = m[1], slug = m[2];
    slugDate[slug] = date;
    if (!domainLatest[domain] || date > domainLatest[domain]) domainLatest[domain] = date;
    if (date > globalLatest) globalLatest = date;
  }
}

const slugKeys = Object.keys(slugDate).sort();
const banner = `// AUTO-GENERATED by scripts/generate-sitemap-lastmod.mjs — DO NOT EDIT BY HAND.\n// slug → 발행일(최초 커밋일). 재생성: node scripts/generate-sitemap-lastmod.mjs\n`;
let ts = banner;
ts += `export const SITE_LASTMOD = '${globalLatest}';\n`;
ts += `export const DOMAIN_LASTMOD: Record<string, string> = {\n`;
for (const d of Object.keys(domainLatest).sort()) ts += `  '${d}': '${domainLatest[d]}',\n`;
ts += `};\n`;
ts += `export const SPOKE_LASTMOD: Record<string, string> = {\n`;
for (const s of slugKeys) ts += `  '${s}': '${slugDate[s]}',\n`;
ts += `};\n`;
writeFileSync(OUT, ts, 'utf8');

// 분포 리포트
const dist = {};
for (const s of slugKeys) { const mo = slugDate[s].slice(0, 7); dist[mo] = (dist[mo] || 0) + 1; }
console.log(`slug 매핑: ${slugKeys.length} | 도메인: ${Object.keys(domainLatest).length} | 전역 최신: ${globalLatest}`);
console.log('월별 발행 분포:');
for (const mo of Object.keys(dist).sort()) console.log(`  ${mo}: ${dist[mo]}`);
console.log(`\n출력: ${OUT}`);
